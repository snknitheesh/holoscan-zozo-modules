"""Write src/dictionary_codes.cpp: every predefined ArUco dictionary's marker codes.

The codes are read from OpenCV's predefined dictionaries, by rendering each marker one pixel per
cell, so the bit order is the printed one: row by row from the top-left cell, the first cell in
the most significant bit, 1 for a white cell. The module does not use OpenCV; this tool runs only
when the tables change, in an environment with the pinned OpenCV:

    python3 -m pip install opencv-python-headless==4.12.0.88
    python3 modules/fiducials/tools/generate_dictionaries.py > modules/fiducials/src/dictionary_codes.cpp

OpenCV's AprilTag dictionaries hold each tag turned a half turn from how the AprilTag library
draws it (same ids, other corners first); the tool turns them back, so a tag's corners and pose
follow the AprilTag library's own images, as holoscan-apriltag reports them.

The 50, 100 and 250 marker ArUco dictionaries are the first markers of the 1000 marker ones; the
tool checks that and stores only the 1000. Each named dictionary keeps OpenCV's
maxCorrectionBits, except the AprilTag families, for which OpenCV stores 0: they get
(d - 1) / 2 for the family's smallest distance d between two codes in any rotation, which is what
the AprilTag library corrects at most.
"""

import sys

import cv2
import numpy as np

ARUCO = cv2.aruco
PINNED_OPENCV = "4.12.0"

# Each table: the C++ name, OpenCV's dictionary holding all of it.
TABLES = [
    ("k4x4", "DICT_4X4_1000"),
    ("k5x5", "DICT_5X5_1000"),
    ("k6x6", "DICT_6X6_1000"),
    ("k7x7", "DICT_7X7_1000"),
    ("kArucoOriginal", "DICT_ARUCO_ORIGINAL"),
    ("kArucoMip36h12", "DICT_ARUCO_MIP_36h12"),
    ("kAprilTag16h5", "DICT_APRILTAG_16h5"),
    ("kAprilTag25h9", "DICT_APRILTAG_25h9"),
    ("kAprilTag36h10", "DICT_APRILTAG_36h10"),
    ("kAprilTag36h11", "DICT_APRILTAG_36h11"),
]

# Each named dictionary: its name (OpenCV's), its table, and whether it is an AprilTag family.
DICTIONARIES = [
    (f"DICT_{n}X{n}_{count}", f"k{n}x{n}", False)
    for n in (4, 5, 6, 7)
    for count in (50, 100, 250, 1000)
] + [
    ("DICT_ARUCO_ORIGINAL", "kArucoOriginal", False),
    ("DICT_ARUCO_MIP_36h12", "kArucoMip36h12", False),
    ("DICT_APRILTAG_16h5", "kAprilTag16h5", True),
    ("DICT_APRILTAG_25h9", "kAprilTag25h9", True),
    ("DICT_APRILTAG_36h10", "kAprilTag36h10", True),
    ("DICT_APRILTAG_36h11", "kAprilTag36h11", True),
]


def dictionary(name: str):
    return ARUCO.getPredefinedDictionary(getattr(ARUCO, name))


def grids(name: str) -> np.ndarray:
    """Every marker's cells, [markers, n, n], 1 for white, AprilTag tags as AprilTag draws them."""
    d = dictionary(name)
    n = d.markerSize
    result = []
    for marker in range(d.bytesList.shape[0]):
        image = ARUCO.generateImageMarker(d, marker, n + 2, borderBits=1)
        if image.shape != (n + 2, n + 2) or image[0].any() or image[-1].any():
            sys.exit(f"{name} {marker}: unexpected rendering")
        cells = (image[1:-1, 1:-1] > 127).astype(np.uint8)
        result.append(np.rot90(cells, 2) if "APRILTAG" in name else cells)
    return np.array(result)


def pack(grid: np.ndarray) -> int:
    code = 0
    for bit in grid.flatten():
        code = (code << 1) | int(bit)
    return code


def min_distance(cells: np.ndarray) -> int:
    """Smallest Hamming distance between two markers, the second in any rotation."""
    flat = [cells.reshape(len(cells), -1)]
    flat += [np.rot90(cells, k, axes=(1, 2)).reshape(len(cells), -1) for k in (1, 2, 3)]
    best = cells.shape[1] * cells.shape[2]
    for k, rotated in enumerate(flat):
        for i in range(len(cells)):
            distances = (rotated != flat[0][i]).sum(axis=1)
            if k == 0:
                distances[i] = best  # A marker against itself, unrotated.
            best = min(best, int(distances.min()))
    return best


def main() -> None:
    if not cv2.__version__.startswith(PINNED_OPENCV):
        sys.exit(f"needs OpenCV {PINNED_OPENCV}, found {cv2.__version__}")
    cells = {table: grids(source) for table, source in TABLES}
    out = sys.stdout
    out.write(
        "// SPDX-FileCopyrightText: Copyright (c) 2026 zozo\n"
        "// SPDX-License-Identifier: Apache-2.0\n"
        "//\n"
        "// Generated by tools/generate_dictionaries.py from OpenCV "
        f"{cv2.__version__}'s predefined\n"
        "// dictionaries (Apache-2.0; see NOTICE). Do not edit.\n"
        "//\n"
        "// Each code is a marker's inner cells row by row from the top-left one, the first in "
        "the\n"
        "// most significant bit, 1 for white.\n\n"
        "#include <array>\n#include <cstdint>\n\n"
        '#include "dictionary_codes.hpp"\n\n'
        "namespace holoscan::fiducials {\nnamespace {\n\n// clang-format off\n"
    )
    for table, source in TABLES:
        codes = [pack(grid) for grid in cells[table]]
        digits = (cells[table].shape[1] ** 2 + 3) // 4
        out.write(f"// {source}\nconstexpr std::array<std::uint64_t, {len(codes)}> {table}{{\n")
        per_line = max(1, 96 // (digits + 6))
        for start in range(0, len(codes), per_line):
            row = ", ".join(f"0x{code:0{digits}x}" for code in codes[start : start + per_line])
            out.write(f"    {row},\n")
        out.write("};\n\n")
    out.write("// clang-format on\n\n}  // namespace\n\n")
    out.write(
        "const std::array<DictionaryTable, "
        f"{len(DICTIONARIES)}>& dictionary_tables() {{\n"
        f"  static constexpr std::array<DictionaryTable, {len(DICTIONARIES)}> kTables{{{{\n"
    )
    for name, table, apriltag in DICTIONARIES:
        d = dictionary(name)
        count = d.bytesList.shape[0]
        if not np.array_equal(grids(name), cells[table][:count]):
            sys.exit(f"{name} is not the first {count} markers of its table")
        correction = (min_distance(cells[table]) - 1) // 2 if apriltag else d.maxCorrectionBits
        out.write(f'      {{"{name}", {d.markerSize}, {count}, {correction}, {table}.data()}},\n')
    out.write("  }};\n  return kTables;\n}\n\n}  // namespace holoscan::fiducials\n")


if __name__ == "__main__":
    main()
